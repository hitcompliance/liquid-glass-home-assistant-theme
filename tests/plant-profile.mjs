import assert from 'node:assert/strict';
import {PLANT_METRICS,plantReading,numericState,fertilityAdvice} from '../src/dash6/plant-profile.js';
const now=Date.now(),state=v=>({state:String(v),last_updated:new Date(now).toISOString()}),metric=k=>PLANT_METRICS.find(m=>m.key===k),read=(k,v,opts={})=>plantReading(metric(k),state(v),{now,...opts});
assert.equal(read('temperature',20).kind,'good');
assert.equal(read('temperature',30).kind,'good');
assert.equal(read('temperature',19).delta,-1);
assert.equal(read('temperature',31).delta,1);
assert.equal(read('moisture',24).delta,-1);
assert.equal(read('illuminance',100000).kind,'good','Full sun has no invented upper optimum');
assert.equal(read('illuminance',0,{night:true}).kind,'night');
assert.equal(read('illuminance',0).kind,'attention','Real zero must not disappear');
assert.equal(read('conductivity',484).kind,'good');
const advice=(ec,moisture=40,temp=25)=>fertilityAdvice(read('conductivity',ec),read('moisture',moisture),read('temperature',temp),metric('conductivity'),metric('moisture'),metric('temperature'));
assert.equal(advice(327,8).title,'Noch nicht düngen','Dry probe must not trigger fertilizer from low EC');
assert.equal(advice(327,40).title,'Düngung prüfen');
assert.equal(advice(350,40).title,'Kein Düngehinweis');
assert.equal(advice(2000,40).title,'Kein Düngehinweis');
assert.equal(advice(2001,40).title,'Nicht weiter düngen');
assert.equal(advice(327,70).title,'Düngung zurückstellen');
assert.equal(advice(327,40,15).title,'Düngung zurückstellen');
assert.equal(advice(327,'unknown').title,'Düngebedarf offen');
assert.equal(advice('unavailable',40).title,'Düngebedarf offen');
assert.equal(advice(0,40).title,'Düngung prüfen','Real zero is a measured low EC, not a missing value');
const staleEC=plantReading(metric('conductivity'),{state:'300',last_updated:new Date(now-7*3600000).toISOString()},{now});
assert.equal(fertilityAdvice(staleEC,read('moisture',40),read('temperature',25),metric('conductivity'),metric('moisture'),metric('temperature')).title,'Düngebedarf offen');
for(const s of ['unknown','unavailable','',' ',null,undefined])assert.equal(numericState({state:s}),null);
assert.equal(plantReading(metric('temperature'),{state:'25',last_updated:new Date(now-7*3600000).toISOString()},{now}).kind,'stale');
assert.equal(plantReading(metric('temperature'),{state:'25',last_updated:new Date(now-7*3600000).toISOString(),last_reported:new Date(now).toISOString()},{now}).kind,'good','Unchanged but recently reported is fresh');
console.log('Plant ranges, missing/stale data, zero, night and conditional fertilizer advice passed.');
