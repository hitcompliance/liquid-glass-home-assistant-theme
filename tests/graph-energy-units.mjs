import assert from 'node:assert/strict';
import {Native} from './graph-continuity.mjs';
import {configuredGraph,resolveGraphSettings} from '../src/dash6/graph-settings.js';
const hass={states:{'sensor.fan':{attributes:{device_class:'energy',state_class:'total_increasing',unit_of_measurement:'Wh'}},'sensor.room':{attributes:{device_class:'energy',state_class:'total',unit_of_measurement:'kWh'}},'sensor.power':{attributes:{device_class:'power',unit_of_measurement:'W'}}}};
const source={series:[{entity:'sensor.fan',unit:'kWh',type:'column',statistics:{type:'change',period:'5minute'},group_by:{func:'sum',duration:'15min'}},{entity:'sensor.room',unit:'kWh',type:'line',statistics:{type:'change',period:'5minute'}},{entity:'sensor.power',unit:'W',type:'line'}]};
const snapshot=structuredClone(source),settings=resolveGraphSettings(source,'sidebar',{getPropertyValue:()=>''});
const configured=configuredGraph(source,settings,hass);
const native=new Native();native._config={...configured.series[0],fill_raw:'null'};
assert.deepEqual(native._transformAndFill(4,{},null),[.004,.004]);
assert.ok(native._transformAndFill(9,{},null).every(v=>Math.abs(v-.009)<1e-12));
assert.deepEqual(native._transformAndFill(0,{},null),[0,0]);
for(const value of [null,undefined,'','unknown','unavailable'])assert.equal(native._transformAndFill(value,{},null)[1],null);
assert.ok(Math.abs(native._sum([[0,.004],[1,.005]])-.009)<1e-12);
assert.equal(configured.cache,false);
assert.equal(configured.series[1].transform,undefined);
assert.equal(configured.series[2].transform,undefined);
assert.equal(configured.series[0].group_by.func,'sum');
assert.deepEqual(configured.series[0].statistics,source.series[0].statistics);
assert.deepEqual(source,snapshot);
const twice=configuredGraph(configured,settings,hass);assert.equal(twice.series[0].transform,configured.series[0].transform,'must not convert twice');
const explicit={series:[{...source.series[0],transform:'return x / 1000;'}]};assert.equal(configuredGraph(explicit,settings,hass).series[0].transform,explicit.series[0].transform);
console.log('PASS: installed Apex statistics parser converts 4 Wh to 0.004 kWh, correct summing, zero/outages, cache isolation, no double conversion; native statistics, kWh and watts unchanged.');
